"use server";

import { revalidatePath } from "next/cache";
import { z } from "zod";
import { requireRole } from "@/lib/auth/dal";
import { createClient } from "@/lib/supabase/server";
import { jobFormSchema, toJobColumns } from "./job-schema";
import { verificationFormSchema } from "./verification-schema";
import type { ActionResult, ResumeLinkResult } from "./result";

/**
 * Stage E2 server actions: company profile, job create/edit/status, student application, resume links.
 * Each action checks the role on the server, validates the input, then writes AS THE USER so that
 * RLS and the guard triggers (jobs_guard, applications_guard) make the final decision.
 */

const fail = (message: string): ActionResult => ({ ok: false, message });
const uuid = z.uuid();
const SIZE_RANGES = ["1-10", "11-50", "51-200", "201-500", "501-1000", "1000+"] as const;

const companyFormSchema = z.object({
  name: z.string().trim().min(2, "Enter your company name (2+ characters).").max(120, "Company name must be 120 characters or fewer."),
  industry: z.string().trim().max(80, "Industry must be 80 characters or fewer.").optional(),
  sizeRange: z.enum([...SIZE_RANGES, ""]).optional(),
  location: z.string().trim().max(100, "Location must be 100 characters or fewer.").optional(),
  website: z
    .string()
    .trim()
    .max(200)
    .refine((v) => v === "" || /^https?:\/\/[^\s]+\.[^\s]+$/i.test(v), "Website must start with https:// (or leave it empty).")
    .optional(),
  about: z.string().trim().max(2000, "About must be 2000 characters or fewer.").optional(),
});

const nullIfEmpty = (v: string | undefined) => (v && v.trim() !== "" ? v.trim() : null);

export async function saveCompanyAction(payload: unknown): Promise<ActionResult> {
  const viewer = await requireRole("employer");
  const parsed = companyFormSchema.safeParse(payload);
  if (!parsed.success) return fail(parsed.error.issues[0]?.message ?? "Please check the company details.");
  const d = parsed.data;
  const columns = {
    name: d.name,
    industry: nullIfEmpty(d.industry),
    size_range: d.sizeRange ? d.sizeRange : null,
    location: nullIfEmpty(d.location),
    website: nullIfEmpty(d.website),
    about: nullIfEmpty(d.about),
  };

  const supabase = await createClient();
  const { data: existing } = await supabase.from("companies").select("id").eq("owner_id", viewer.id).maybeSingle();

  if (existing) {
    // The guard trigger resets verification if an approved company changes its name or website.
    const { data, error } = await supabase.from("companies").update(columns).eq("id", existing.id).select("id, verification_status");
    if (error || !data?.length) return fail("We could not save the company profile. Please try again.");
    revalidatePath("/employer");
    revalidatePath("/employer/company");
    revalidatePath("/employer/jobs");
    return { ok: true, message: "Company profile saved." };
  }

  // slug is generated by the database trigger (companies_guard) when it is empty.
  const { error } = await supabase.from("companies").insert({ ...columns, owner_id: viewer.id, slug: "" });
  if (error) {
    if (error.code === "23505") return fail("You already have a company profile.");
    return fail("We could not create the company profile. Please try again.");
  }
  revalidatePath("/employer");
  revalidatePath("/employer/company");
  return { ok: true, message: "Company created. You can now post roles." };
}

export async function saveJobAction(payload: unknown): Promise<ActionResult> {
  const viewer = await requireRole("employer");
  const body = z.object({ jobId: uuid.optional(), form: z.unknown() }).safeParse(payload);
  if (!body.success) return fail("We could not read the form. Please refresh and try again.");

  const parsed = jobFormSchema.safeParse(body.data.form);
  if (!parsed.success) return fail(parsed.error.issues[0]?.message ?? "Please check the highlighted fields.");
  const { intent } = parsed.data;
  const columns = { ...toJobColumns(parsed.data), status: intent === "publish" ? "published" : "draft" };

  const supabase = await createClient();
  let status: string | undefined;

  if (body.data.jobId) {
    // RLS allows the update only for the owner's company; any other job matches zero rows.
    const { data, error } = await supabase.from("jobs").update(columns).eq("id", body.data.jobId).select("id, status");
    if (error) return fail(error.code === "P0001" || error.code === "42501" ? error.message : "The listing could not be saved. Please try again.");
    if (!data?.length) return fail("You can only edit your own listings.");
    status = data[0].status;
  } else {
    // Filter by owner: approved companies are visible to everyone under RLS, so do not rely on RLS alone here.
    const { data: company } = await supabase.from("companies").select("id").eq("owner_id", viewer.id).maybeSingle();
    if (!company) return fail("Create your company profile before posting a role.");
    const { data, error } = await supabase.from("jobs").insert({ ...columns, company_id: company.id }).select("id, status");
    if (error) return fail(error.code === "P0001" || error.code === "23514" ? error.message : "The listing could not be saved. Please try again.");
    status = data?.[0]?.status;
  }

  revalidatePath("/employer/jobs");
  revalidatePath("/jobs");
  if (status === "pending_review") return { ok: true, message: "Sent for review. It goes live after an admin approves it." };
  if (status === "published") return { ok: true, message: "Published." };
  return { ok: true, message: "Draft saved." };
}

export async function setMyJobStatusAction(payload: unknown): Promise<ActionResult> {
  await requireRole("employer");
  const parsed = z.object({ jobId: uuid, status: z.enum(["paused", "closed", "published"]) }).safeParse(payload);
  if (!parsed.success) return fail("Invalid request.");
  const supabase = await createClient();
  const { data, error } = await supabase.from("jobs").update({ status: parsed.data.status }).eq("id", parsed.data.jobId).select("id, status");
  if (error) return fail("That change is not allowed for this listing.");
  if (!data?.length) return fail("You can only change your own listings.");
  revalidatePath("/employer/jobs");
  revalidatePath("/jobs");
  revalidatePath(`/jobs/${parsed.data.jobId}`);
  if (data[0].status === "pending_review") return { ok: true, message: "Sent for review again." };
  return { ok: true, message: parsed.data.status === "paused" ? "Paused." : parsed.data.status === "closed" ? "Closed." : "Live again." };
}

export async function applyToJobAction(payload: unknown): Promise<ActionResult> {
  const viewer = await requireRole("student");
  const parsed = z
    .object({
      jobId: uuid,
      resumeId: z.union([uuid, z.literal("")]).optional(),
      coverNote: z.string().trim().max(2000, "Your note must be 2000 characters or fewer.").optional(),
    })
    .safeParse(payload);
  if (!parsed.success) return fail(parsed.error.issues[0]?.message ?? "Please check your application.");

  const supabase = await createClient();
  // student_id is always the signed-in user. The guard trigger rejects any other value.
  const { data, error } = await supabase
    .from("applications")
    .insert({
      job_id: parsed.data.jobId,
      student_id: viewer.id,
      resume_id: parsed.data.resumeId || null,
      cover_note: nullIfEmpty(parsed.data.coverNote),
    })
    .select("id");

  if (error) {
    // The unique (job_id, student_id) constraint is the real duplicate guard. It also covers two
    // submissions at the same moment: only one insert can succeed.
    if (error.code === "23505") return fail("You have already applied to this role.");
    if (error.code === "P0001" || error.code === "42501") return fail(error.message);
    return fail("Your application could not be sent. Please try again.");
  }
  if (!data?.length) return fail("Your application could not be sent. Please try again.");

  revalidatePath("/student/applications");
  revalidatePath(`/jobs/${parsed.data.jobId}`);
  return { ok: true, message: "Application sent. You can track it in My applications." };
}

/** Short-lived link to a resume. Storage RLS only allows it for an employer whose job the student applied to. */
export async function getResumeLinkAction(payload: unknown): Promise<ResumeLinkResult> {
  await requireRole("employer");
  const parsed = z.object({ resumeId: uuid }).safeParse(payload);
  if (!parsed.success) return { ok: false, message: "Invalid resume." };
  const supabase = await createClient();
  // RLS: an employer can read a resume row only if it is attached to one of their applications.
  const { data: resume } = await supabase.from("resumes").select("storage_path").eq("id", parsed.data.resumeId).maybeSingle();
  if (!resume?.storage_path) return { ok: false, message: "This resume is not available to you." };
  const { data, error } = await supabase.storage.from("resumes").createSignedUrl(resume.storage_path, 300);
  if (error || !data?.signedUrl) return { ok: false, message: "The resume could not be opened. Please try again." };
  return { ok: true, url: data.signedUrl };
}

/** Employer asks an admin to verify their company. The database forces status = pending and records the submitter. */
export async function requestCompanyVerificationAction(payload: unknown): Promise<ActionResult> {
  const viewer = await requireRole("employer");
  const parsed = verificationFormSchema.safeParse(payload);
  if (!parsed.success) return fail(parsed.error.issues[0]?.message ?? "Please check the verification details.");
  const d = parsed.data;

  const supabase = await createClient();
  const { data: company } = await supabase.from("companies").select("id, verification_status").eq("owner_id", viewer.id).maybeSingle();
  if (!company) return fail("Create your company profile before requesting verification.");
  if (company.verification_status === "approved") return fail("Your company is already verified.");

  const { error } = await supabase.from("company_verifications").insert({
    company_id: company.id,
    submitted_by: viewer.id,
    business_email: d.businessEmail,
    registration_number: nullIfEmpty(d.registrationNumber),
    notes: nullIfEmpty(d.notes),
  });
  if (error) {
    // Only one pending request per company is allowed (unique partial index).
    if (error.code === "23505") return fail("A verification request is already waiting for review.");
    return fail("The request could not be sent. Please try again.");
  }
  revalidatePath("/employer/company");
  return { ok: true, message: "Verification request sent. An admin will review it." };
}
